// Packs the built screen (public/) into src/server/web-assets.ts so the server can serve it itself.
// Why: on Vercel's Hono setup, files that the build writes into public/ were not served (404 on 13 Nov 2026),
// so the server delivers the screen. Runs only on Vercel (VERCEL=1) or with --force, so local builds keep the
// small committed stub and git stays clean.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

if (!process.env.VERCEL && !process.argv.includes("--force")) {
  console.log("embed-web: skipped (not on Vercel; pass --force to run)");
  process.exit(0);
}
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".svg": "image/svg+xml", ".json": "application/json", ".png": "image/png", ".ico": "image/x-icon", ".woff2": "font/woff2" };
const TEXT = new Set([".html", ".js", ".css", ".svg", ".json"]);
const root = "public";
const files = {};
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else {
      const ext = extname(p);
      const text = TEXT.has(ext);
      files["/" + relative(root, p).split("\\").join("/")] = { type: TYPES[ext] ?? "application/octet-stream", base64: !text, body: readFileSync(p, text ? "utf8" : "base64") };
    }
  }
};
walk(root);
writeFileSync("src/server/web-assets.ts", `// Generated by scripts/embed-web.mjs during the Vercel build. The committed version is an empty stub.\nexport const WEB_FILES: Record<string, { type: string; base64: boolean; body: string }> = ${JSON.stringify(files)};\n`);
console.log(`embed-web: packed ${Object.keys(files).length} files`);
